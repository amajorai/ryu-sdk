"""The public ``ryu.<namespace>.<method>`` surface, as committed in ``surface.json``.

The public docs guard (apps/fumadocs/src/lib/standalone-sdk-docs.test.ts)
reads ``surface.json`` to check every ``ryu.<ns>.<method>`` chain in a Python
code sample; ``tests/test_services_surface.py`` fails when the file and the
client disagree. Regenerate with::

    PYTHONPATH=bindings/python python -m ryu_sdk.services._surface > bindings/python/ryu_sdk/services/surface.json
"""

from __future__ import annotations

import json
from typing import Any

from ._base import Resource
from .client import NAMESPACES, Ryu


def _walk(prefix: str, target: Any, out: set[str]) -> None:
    for name in dir(target):
        if name.startswith("_"):
            continue
        value = getattr(target, name)
        path = f"{prefix}.{name}"
        if isinstance(value, Resource):
            out.add(path)
            _walk(path, value, out)
        elif callable(value):
            out.add(path)


def surface() -> list[str]:
    """Every dotted path under ``ryu.`` that a sample may name (namespaces, resources and methods)."""
    ryu = Ryu(env=False)
    paths: set[str] = {"safe", "webhooks", "is_configured", "can_call_without_credentials", "close"}
    for name in dir(ryu.webhooks):
        if not name.startswith("_"):
            paths.add(f"webhooks.{name}")
    for attribute in NAMESPACES:
        paths.add(attribute)
        _walk(attribute, getattr(ryu, attribute), paths)
    return sorted(paths)


def surface_document() -> dict[str, Any]:
    return {
        "description": "Every ryu.<namespace>.<method> path of the Python client (ryu_sdk.services.Ryu). Generated by ryu_sdk/services/_surface.py.",
        "paths": surface(),
    }


if __name__ == "__main__":
    print(json.dumps(surface_document(), indent=2))
