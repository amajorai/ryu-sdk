/**
 * The pure-JS stand-in for `@ryuhq/sdk-native` that `ryu build` links into
 * serverless and edge bundles (Vercel, Netlify, Cloudflare Workers).
 *
 * The native addon is a platform-specific `.node` binary: it cannot load on
 * Workers at all, and a binary built on the developer's machine is the wrong
 * platform for a Vercel or Netlify function. This shim reimplements the
 * addon's gateway surface in plain JavaScript: gateway URL/token resolution
 * and the egress guard from `crates/sdk/core/src/gateway.rs` (the blocklist is
 * held in lockstep by `build.test.ts`), and fetch-based `ModelClient` /
 * `EmbeddingClient` that speak the same OpenAI-compatible wire protocol as
 * `crates/sdk/core/src/{model,embedding}.rs`, so `ctx.gateway` and
 * `defineModel` work in serverless bundles. Manifest validation is not
 * reimplemented: it throws a clear error naming the Node-based targets that
 * keep the real addon.
 */

/** Mirrors `BLOCKED_PROVIDER_PATTERNS` in `crates/sdk/core/src/gateway.rs`. */
export const EDGE_BLOCKED_PROVIDER_PATTERNS = [
	"api\\.openai\\.com",
	"api\\.anthropic\\.com",
	"generativelanguage\\.googleapis\\.com",
	"api\\.cohere\\.ai",
	"api\\.mistral\\.ai",
	"openrouter\\.ai",
	"api\\.groq\\.com",
	"api\\.together\\.xyz",
	"api\\.replicate\\.com",
	"api\\.perplexity\\.ai",
] as const;

/** The shim module's source, written next to the generated entry at build time. */
export function edgeNativeShimSource(): string {
	const patterns = EDGE_BLOCKED_PROVIDER_PATTERNS.map(
		(pattern) => `\tnew RegExp(${JSON.stringify(pattern)}, "i"),`
	).join("\n");
	return `// Generated by \`ryu build\`: pure-JS stand-in for @ryuhq/sdk-native in serverless bundles.
const DEFAULT_GATEWAY_URL = "http://127.0.0.1:7981";
const BLOCKED = [
${patterns}
];

function env(key) {
	const value = globalThis.process?.env?.[key];
	const trimmed = typeof value === "string" ? value.trim() : "";
	return trimmed === "" ? undefined : trimmed;
}

export function resolveGatewayUrl() {
	return env("RYU_GATEWAY_URL") ?? DEFAULT_GATEWAY_URL;
}

export function resolveGatewayToken() {
	return env("RYU_GATEWAY_TOKEN") ?? null;
}

export function assertAllowedEgress(url) {
	if (BLOCKED.some((pattern) => pattern.test(url))) {
		throw new Error(
			\`[ryu-sdk] direct provider egress is not allowed: "\${url}". All model calls must route through the Ryu gateway. Set RYU_GATEWAY_URL to your gateway base URL, or omit baseUrl to use the default (\${DEFAULT_GATEWAY_URL}). Provider credentials belong in the gateway, not in SDK config.\`
		);
	}
}

function unavailable(what) {
	return new Error(
		\`[ryu-sdk] \${what} needs the native SDK addon, which serverless builds do not ship. Build with --target node or docker to use \${what}.\`
	);
}

// The gateway clients below speak the same OpenAI-compatible wire protocol as
// the native addon's Rust core: POST {base}/v1/chat/completions and
// {base}/v1/embeddings with an optional bearer token, egress-checked at
// construction.

function gatewayBase(baseUrl) {
	const base = baseUrl ?? resolveGatewayUrl();
	assertAllowedEgress(base);
	return base.replace(/\\/+$/, "");
}

async function gatewayPost(url, token, body) {
	const headers = { "content-type": "application/json" };
	if (token) {
		headers.authorization = \`Bearer \${token}\`;
	}
	const response = await fetch(url, {
		method: "POST",
		headers,
		body: JSON.stringify(body),
	});
	if (!response.ok) {
		const text = await response.text().catch(() => "");
		throw new Error(\`gateway returned HTTP \${response.status} from \${url}: \${text}\`);
	}
	return response;
}

function firstChoice(body) {
	const choices = body && Array.isArray(body.choices) ? body.choices : [];
	return choices[0];
}

/** Parse one SSE line: a delta, the [DONE] terminator, or undefined to skip. */
export function parseSseLine(line) {
	const trimmed = line.trim();
	if (!trimmed.startsWith("data:")) {
		return undefined;
	}
	const payload = trimmed.slice(5).trim();
	if (payload === "[DONE]") {
		return "done";
	}
	let chunk;
	try {
		chunk = JSON.parse(payload);
	} catch {
		return undefined;
	}
	const choice = firstChoice(chunk);
	if (!choice) {
		return undefined;
	}
	return {
		content: choice.delta?.content ?? "",
		finishReason: choice.finish_reason ?? undefined,
	};
}

export class ModelClient {
	#model;
	#token;
	#url;

	constructor(model, baseUrl, token) {
		this.#url = \`\${gatewayBase(baseUrl ?? undefined)}/v1/chat/completions\`;
		this.#model = model;
		this.#token = token ?? resolveGatewayToken();
	}

	async chat(messages) {
		const response = await gatewayPost(this.#url, this.#token, {
			model: this.#model,
			messages,
			stream: false,
		});
		const body = await response.json();
		const choice = firstChoice(body);
		const usage = body?.usage;
		return {
			content: choice?.message?.content ?? "",
			finishReason: choice?.finish_reason ?? undefined,
			promptTokens: usage ? (usage.prompt_tokens ?? 0) : undefined,
			completionTokens: usage ? (usage.completion_tokens ?? 0) : undefined,
			totalTokens: usage ? (usage.total_tokens ?? 0) : undefined,
		};
	}

	stream(messages, callback) {
		this.#pump(messages, callback).catch((error) => {
			callback(error instanceof Error ? error : new Error(String(error)), undefined);
		});
	}

	async #pump(messages, callback) {
		const response = await gatewayPost(this.#url, this.#token, {
			model: this.#model,
			messages,
			stream: true,
		});
		if (!response.body) {
			callback(null, null);
			return;
		}
		const reader = response.body.getReader();
		const decoder = new TextDecoder();
		let buffer = "";
		while (true) {
			const { done, value } = await reader.read();
			buffer += decoder.decode(value, { stream: !done });
			let newline = buffer.indexOf("\\n");
			while (newline >= 0) {
				const parsed = parseSseLine(buffer.slice(0, newline));
				buffer = buffer.slice(newline + 1);
				if (parsed === "done") {
					await reader.cancel().catch(() => undefined);
					callback(null, null);
					return;
				}
				if (parsed) {
					callback(null, parsed);
				}
				newline = buffer.indexOf("\\n");
			}
			if (done) {
				break;
			}
		}
		const tail = parseSseLine(buffer);
		if (tail && tail !== "done") {
			callback(null, tail);
		}
		callback(null, null);
	}
}

export class EmbeddingClient {
	#model;
	#token;
	#url;

	constructor(model, baseUrl, token) {
		this.#url = \`\${gatewayBase(baseUrl ?? undefined)}/v1/embeddings\`;
		this.#model = model;
		this.#token = token ?? resolveGatewayToken();
	}

	async embed(inputs) {
		const response = await gatewayPost(this.#url, this.#token, {
			model: this.#model,
			input: inputs,
		});
		const body = await response.json();
		const data = Array.isArray(body?.data) ? body.data : [];
		const embeddings = data
			.map((item, fallbackIndex) => ({
				index: typeof item?.index === "number" ? item.index : fallbackIndex,
				vector: Array.isArray(item?.embedding) ? item.embedding : [],
			}))
			.sort((left, right) => left.index - right.index);
		const usage = body?.usage;
		return {
			embeddings,
			promptTokens: usage ? (usage.prompt_tokens ?? 0) : undefined,
			totalTokens: usage ? (usage.total_tokens ?? 0) : undefined,
		};
	}
}

export function validatePluginId() {
	throw unavailable("validatePluginId");
}

export function parseAndValidateManifest() {
	throw unavailable("parseAndValidateManifest");
}

export function pluginManifestJsonSchema() {
	throw unavailable("pluginManifestJsonSchema");
}
`;
}
