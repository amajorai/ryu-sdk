export type { BundleRequest, Bundler } from "./bundler.ts";
export { bunBundler };

// ── Build ─────────────────────────────────────────────────────────────────────

/** Options for {@link buildProject}. */
export interface BuildOptions {
	bundler?: Bundler;
	/** Absolute path to the project entry. */
	entry: string;
	/** Deployment name. */
	name: string;
	/** Version range of `@ryuhq/sdk-native` for Node targets. */
	nativeVersion?: string;
	/** Override for `@ryuhq/sdk/server/node` (tests point at sources). */
	nodeModule?: string;
	/** Absolute output root; each target writes to `<outDir>/<target>`. */
	outDir: string;
	/** Override for `@ryuhq/sdk/server` (tests point at sources). */
	serverModule?: string;
	target: BuildTarget;
}

/** What one target build produced. */
export interface BuildResult {
	/** Absolute directory holding the target's artifacts. */
	dir: string;
	/** Every file written, relative to `dir`, sorted. */
	files: string[];
	hint: string;
	target: BuildTarget;
}

function importSpecifier(fromDir: string, file: string): string {
	const rel = relative(fromDir, file).split(sep).join("/");
	return rel.startsWith(".") ? rel : `./${rel}`;
}

/**
 * The `@ryuhq/sdk-native` range a generated package.json depends on. The SDK
 * and its native addon release in lockstep (held by `build.test.ts` against
 * both package.json versions), so this tracks the SDK's own version.
 */
export const NATIVE_VERSION_RANGE = "^0.5.0";

/** Build one target. */
export async function buildProject(
	options: BuildOptions
): Promise<BuildResult> {
	if (!existsSync(options.entry)) {
		throw new Error(`project entry not found: ${options.entry}`);
	}
	const dir = join(options.outDir, options.target);
	const work = join(options.outDir, ".ryu-build", options.target);
	rmSync(dir, { recursive: true, force: true });
	rmSync(work, { recursive: true, force: true });
	mkdirSync(work, { recursive: true });

	const plan = planTarget(options.target, {
		entryImport: importSpecifier(work, options.entry),
		name: options.name,
		nativeVersion: options.nativeVersion ?? NATIVE_VERSION_RANGE,
		serverModule: options.serverModule ?? "@ryuhq/sdk/server",
		nodeModule: options.nodeModule ?? "@ryuhq/sdk/server/node",
	});

	const entrypoint = join(work, "entry.mjs");
	writeFileSync(entrypoint, plan.entrySource);
	let shimPath: string | undefined;
	if (plan.native === "shim") {
		shimPath = join(work, "sdk-native-edge.mjs");
		writeFileSync(shimPath, edgeNativeShimSource());
	}

	try {
		await (options.bundler ?? bunBundler)({
			entrypoint,
			outfile: join(dir, plan.bundleFile),
			platform: plan.platform,
			external: plan.native === "external" ? [NATIVE_PACKAGE] : [],
			shimPath,
		});
	} finally {
		rmSync(join(options.outDir, ".ryu-build"), {
			recursive: true,
			force: true,
		});
	}

	for (const [file, content] of Object.entries(plan.files)) {
		const path = join(dir, file);
		mkdirSync(dirname(path), { recursive: true });
		writeFileSync(path, content);
	}

	const files = [...Object.keys(plan.files), plan.bundleFile].sort();
	return { target: options.target, dir, files, hint: plan.hint };
}

// ── CLI ───────────────────────────────────────────────────────────────────────

/** Parsed `ryu build` arguments. */
export interface BuildArgs {
	entry: string;
	name?: string;
	outDir: string;
	targets: BuildTarget[];
}

const targetSchema = z.enum(BUILD_TARGETS);

/** Read a `--flag value` or `--flag=value` option. */
export function readOption(
	args: string[],
	flag: string
): { rest: string[]; value?: string } {
	const rest: string[] = [];
	let value: string | undefined;
	for (let index = 0; index < args.length; index++) {
		const arg = args[index] ?? "";
		if (arg === flag) {
			value = args[index + 1];
			if (value === undefined || value.startsWith("--")) {
				throw new Error(`${flag} requires a value`);
			}
			index += 1;
		} else if (arg.startsWith(`${flag}=`)) {
			value = arg.slice(flag.length + 1);
		} else {
			rest.push(arg);
		}
	}
	return { rest, value };
}

/** Parse `ryu build [entry] --target <t[,t]> [--out <dir>] [--name <n>]`. */
export function parseBuildArgs(args: string[]): BuildArgs {
	const target = readOption(args, "--target");
	const out = readOption(target.rest, "--out");
	const name = readOption(out.rest, "--name");
	const unknown = name.rest.filter((arg) => arg.startsWith("--"));
	if (unknown.length > 0) {
		throw new Error(`unknown option ${unknown[0]}`);
	}
	if (name.rest.length > 1) {
		throw new Error("ryu build takes at most one entry argument");
	}
	if (!target.value) {
		throw new Error(
			`--target is required (one of: ${BUILD_TARGETS.join(", ")})`
		);
	}
	const targets = target.value.split(",").map((raw) => {
		const parsed = targetSchema.safeParse(raw.trim());
		if (!parsed.success) {
			throw new Error(
				`unknown target "${raw}" (expected one of: ${BUILD_TARGETS.join(", ")})`
			);
		}
		return parsed.data;
	});
	return {
		entry: name.rest[0] ?? DEFAULT_ENTRY,
		outDir: out.value ?? DEFAULT_OUT_DIR,
		name: name.value,
		targets: [...new Set(targets)],
	};
}

const packageNameSchema = z.object({ name: z.string().min(1) });

/** The deployment name: `--name`, else the project's package.json name, else the directory. */
export function projectName(root: string, explicit?: string): string {
	if (explicit) {
		return deploymentName(explicit);
	}
	try {
		const pkg = packageNameSchema.safeParse(
			JSON.parse(readFileSync(join(root, "package.json"), "utf8"))
		);
		if (pkg.success) {
			return deploymentName(pkg.data.name);
		}
	} catch {
		// No package.json: fall back to the directory name.
	}
	return deploymentName(basename(resolve(root)));
}

/** `ryu build` entry point. */
export async function commandBuild(
	args: string[],
	cwd: string = process.cwd()
): Promise<BuildResult[]> {
	const parsed = parseBuildArgs(args);
	const name = projectName(cwd, parsed.name);
	const results: BuildResult[] = [];
	for (const target of parsed.targets) {
		const result = await buildProject({
			entry: resolve(cwd, parsed.entry),
			outDir: resolve(cwd, parsed.outDir),
			name,
			target,
		});
		process.stdout.write(
			`built ${target} → ${relative(cwd, result.dir) || "."}\n  next: cd ${relative(cwd, result.dir)} && ${result.hint}\n`
		);
		results.push(result);
	}
	return results;
}
