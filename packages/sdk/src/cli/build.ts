/**
 * `ryu build` — bundle an SDK project into deployable artifacts.
 *
 * The project entry (default `src/ryu.ts`) exports a server, a server config,
 * or named `agents` / `workflows` / `tools` (see `resolveRyuServer`). The built
 * server refuses to start without an `auth` hook unless `RYU_SERVER_PUBLIC=1`
 * is set (`resolveDeployedServer`). For each
 * target the build writes a small generated entry that wraps the project in
 * `createRyuServer`, bundles it into one ES module, and lays out the files the
 * vendor expects:
 *
 *   node        server.mjs + package.json                  `node server.mjs`
 *   docker      the node output + Dockerfile + .dockerignore
 *   vercel      .vercel/output (Build Output API v3)       `vercel deploy --prebuilt`
 *   cloudflare  worker.mjs + wrangler.toml                 `wrangler deploy`
 *   netlify     netlify/functions/ryu.mjs + netlify.toml   `netlify deploy`
 *
 * Node and Docker keep the native SDK addon as a runtime dependency (installed
 * on the target platform). The serverless targets link the pure-JS shim from
 * `edge-native.ts` instead, so the bundle is self-contained.
 *
 * No credentials are read or written: secrets such as `RYU_GATEWAY_TOKEN` are
 * configured in each vendor's own secret store at deploy time.
 */

import {
	existsSync,
	mkdirSync,
	readFileSync,
	rmSync,
	writeFileSync,
} from "node:fs";
import { basename, dirname, join, relative, resolve, sep } from "node:path";
import { z } from "zod";
import { type Bundler, bunBundler } from "./bundler.ts";
import { edgeNativeShimSource } from "./edge-native.ts";

/** Every build target. */
export const BUILD_TARGETS = [
	"node",
	"docker",
	"vercel",
	"cloudflare",
	"netlify",
] as const;

/** A build target. */
export type BuildTarget = (typeof BUILD_TARGETS)[number];

/** Default project entry, relative to the project root. */
export const DEFAULT_ENTRY = "src/ryu.ts";

/** Default output directory, relative to the project root. */
export const DEFAULT_OUT_DIR = ".ryu/build";

/** Cloudflare `compatibility_date` written into wrangler.toml. */
export const CLOUDFLARE_COMPATIBILITY_DATE = "2025-09-01";

/** Vercel Node.js runtime written into `.vc-config.json`. */
export const VERCEL_RUNTIME = "nodejs22.x";

const NATIVE_PACKAGE = "@ryuhq/sdk-native";
const WORKER_NAME_INVALID = /[^a-z0-9-]+/g;
const EDGE_DASHES = /^-+|-+$/g;

/** How a target's bundle links the native addon. */
type NativeMode = "external" | "shim";

/** The files one target produces, before bundling. */
export interface TargetPlan {
	/** Bundle output path, relative to the target directory. */
	bundleFile: string;
	/** The generated entry module that wraps the project. */
	entrySource: string;
	/** Static files to write, relative to the target directory. */
	files: Record<string, string>;
	/** How to run or ship the result. */
	hint: string;
	native: NativeMode;
	/** `node` bundles for Node; `edge` bundles for Workers-style runtimes. */
	platform: "edge" | "node";
}

/** Inputs to {@link planTarget}. */
export interface PlanInput {
	/** Import specifier of the project entry, relative to the generated entry. */
	entryImport: string;
	/** Deployment name (sanitized for each vendor). */
	name: string;
	/** Version range of `@ryuhq/sdk-native` for Node targets. */
	nativeVersion: string;
	/** Module that exports `serve` / `toNodeListener`. */
	nodeModule: string;
	/** Module that exports `resolveDeployedServer`. */
	serverModule: string;
}

const HEADER = (target: BuildTarget) =>
	`// Generated by \`ryu build --target ${target}\`. Do not edit; rebuild instead.`;

function entryPrelude(target: BuildTarget, input: PlanInput): string {
	return [
		HEADER(target),
		`import * as project from ${JSON.stringify(input.entryImport)};`,
		`import { resolveDeployedServer } from ${JSON.stringify(input.serverModule)};`,
	].join("\n");
}

/** A name that every vendor accepts: lowercase letters, digits, dashes. */
export function deploymentName(raw: string): string {
	const cleaned = raw
		.toLowerCase()
		.replace(/^@[^/]+\//, "")
		.replace(WORKER_NAME_INVALID, "-")
		.replace(EDGE_DASHES, "")
		.slice(0, 63)
		.replace(EDGE_DASHES, "");
	return cleaned === "" ? "ryu-app" : cleaned;
}

function nodeEntry(target: BuildTarget, input: PlanInput): string {
	return `${entryPrelude(target, input)}
import { serve } from ${JSON.stringify(input.nodeModule)};

const server = resolveDeployedServer(project);
const port = Number(process.env.PORT ?? 3000);
const hostname = process.env.HOST ?? "0.0.0.0";
const app = await serve({ fetch: server.fetch, port, hostname });
process.stdout.write(\`ryu server listening on \${app.url}\${server.basePath}\\n\`);
const stop = () => {
	app.close().finally(() => process.exit(0));
};
process.once("SIGINT", stop);
process.once("SIGTERM", stop);
`;
}

function nodePackageJson(name: string, nativeVersion: string): string {
	return `${JSON.stringify(
		{
			name,
			private: true,
			type: "module",
			scripts: { start: "node server.mjs" },
			engines: { node: ">=20" },
			dependencies: { [NATIVE_PACKAGE]: nativeVersion },
		},
		null,
		2
	)}\n`;
}

const DOCKERFILE = `# Generated by \`ryu build --target docker\`. Do not edit; rebuild instead.
FROM node:22-bookworm-slim
WORKDIR /app
ENV NODE_ENV=production PORT=3000 HOST=0.0.0.0
COPY package.json ./
RUN npm install --omit=dev --no-audit --no-fund
COPY server.mjs ./
USER node
EXPOSE 3000
CMD ["node", "server.mjs"]
`;

/** Plan the generated files for one target. Pure: no filesystem access. */
export function planTarget(target: BuildTarget, input: PlanInput): TargetPlan {
	const name = deploymentName(input.name);
	switch (target) {
		case "node":
			return {
				platform: "node",
				native: "external",
				bundleFile: "server.mjs",
				entrySource: nodeEntry(target, input),
				files: { "package.json": nodePackageJson(name, input.nativeVersion) },
				hint: "npm install && node server.mjs",
			};
		case "docker":
			return {
				platform: "node",
				native: "external",
				bundleFile: "server.mjs",
				entrySource: nodeEntry(target, input),
				files: {
					"package.json": nodePackageJson(name, input.nativeVersion),
					Dockerfile: DOCKERFILE,
					".dockerignore": "node_modules\nnpm-debug.log\n",
				},
				hint: `docker build -t ${name} . && docker run -p 3000:3000 -e RYU_GATEWAY_URL ${name}`,
			};
		case "vercel":
			return {
				platform: "node",
				native: "shim",
				bundleFile: ".vercel/output/functions/index.func/index.mjs",
				entrySource: `${entryPrelude(target, input)}
import { toNodeListener } from ${JSON.stringify(input.nodeModule)};

export default toNodeListener(resolveDeployedServer(project).fetch);
`,
				files: {
					".vercel/output/config.json": `${JSON.stringify(
						{
							version: 3,
							routes: [
								{ handle: "filesystem" },
								{ src: "/(.*)", dest: "/index" },
							],
						},
						null,
						2
					)}\n`,
					".vercel/output/functions/index.func/.vc-config.json": `${JSON.stringify(
						{
							runtime: VERCEL_RUNTIME,
							handler: "index.mjs",
							launcherType: "Nodejs",
							shouldAddHelpers: false,
							supportsResponseStreaming: true,
						},
						null,
						2
					)}\n`,
				},
				hint: "vercel deploy --prebuilt",
			};
		case "cloudflare":
			return {
				platform: "edge",
				native: "shim",
				bundleFile: "worker.mjs",
				entrySource: `${entryPrelude(target, input)}

const server = resolveDeployedServer(project);

export default {
	fetch(request) {
		return server.fetch(request);
	},
};
`,
				files: {
					"wrangler.toml": `# Generated by \`ryu build --target cloudflare\`. Do not edit; rebuild instead.
name = ${JSON.stringify(name)}
main = "worker.mjs"
compatibility_date = ${JSON.stringify(CLOUDFLARE_COMPATIBILITY_DATE)}
compatibility_flags = ["nodejs_compat"]

# Configuration such as RYU_GATEWAY_URL and RYU_GATEWAY_TOKEN is read from
# process.env. Set secrets with \`wrangler secret put <NAME>\`; never commit them.
`,
				},
				hint: "wrangler deploy",
			};
		case "netlify":
			return {
				platform: "node",
				native: "shim",
				bundleFile: "netlify/functions/ryu.mjs",
				entrySource: `${entryPrelude(target, input)}

const server = resolveDeployedServer(project);

export default (request) => server.fetch(request);

export const config = { path: "/*" };
`,
				files: {
					"netlify.toml": `# Generated by \`ryu build --target netlify\`. Do not edit; rebuild instead.
[build]
  publish = "public"

[functions]
  directory = "netlify/functions"
`,
					"public/.keep": "",
				},
				hint: "netlify deploy",
			};
		default:
			return target satisfies never;
	}
}

